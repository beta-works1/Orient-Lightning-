/** Normalized dealers used by the app (JSON fallback + DB seed). */
export function buildDealerSeed(): Dealer[] {
  return dealerSeedData.map((row) => {
    const phone = row.phone;
    const whatsapp = phone ? phone.replace(/\D/g, "") : null;
    return {
      id: slugId(row.name, row.city),
      name: row.name,
      type: row.type,
      address: row.address,
      city: row.city,
      latitude: row.latitude,
      longitude: row.longitude,
      phone,
      whatsapp,
      hours: row.hours,
      verified: row.verified,
      isWalkIn: row.verified && row.type === "flagship",
    };
  });
}
